
import { useLanguage } from "../../../context/LanguageContext";

export default function BillPrint({ bill }) {
  const { t, language } = useLanguage();

  if (!bill) {
    return null;
  }

  const items = bill.items || [];

  if (items.length === 0) {
    return null;
  }

  const today = new Date(
    bill.createdAt || Date.now()
  ).toLocaleDateString("en-IN");

  const getLocalizedProductName = (item) => {
    if (!item) {
      return "";
    }

    if (language === "hi") {
      return item.nameHi || item.nameEn || "";
    }

    return item.nameEn || item.nameHi || "";
  };

  const getLocalizedUnitName = (item) => {
    if (!item) {
      return "";
    }

    const unitName =
      language === "hi"
        ? item.unitNameHi || item.unitNameEn || ""
        : item.unitNameEn || item.unitNameHi || "";

    if (!unitName) {
      return "";
    }

    if (item.unitShortName) {
      return `${unitName} (${item.unitShortName})`;
    }

    return unitName;
  };

  const hasValidNumber = (value) => {
    if (
      value === "" ||
      value === null ||
      value === undefined
    ) {
      return false;
    }

    return Number.isFinite(Number(value));
  };

  const allItemsValid = items.every((item) => {
    const hasQuantity = hasValidNumber(item.quantity);
    const hasRate = hasValidNumber(item.rate);

    if (!hasQuantity || !hasRate) {
      return false;
    }

    return Number(item.quantity) > 0 && Number(item.rate) >= 0;
  });

  const hasValidTotal =
    bill.total !== "" &&
    bill.total !== null &&
    bill.total !== undefined &&
    Number.isFinite(Number(bill.total));

  const shouldShowTotal = allItemsValid && hasValidTotal;

  return (
    <div className="print-only print-page">
      <div className="print-container">
        {/* ================================
            HEADER
        ================================= */}

        {/* Row 1: Date / Bill Number / Generated By */}
        <div className="print-header-row">
          <div className="print-date">
            {t("date")}: {today}
          </div>

          <div className="print-bill-number">
            {t("billNumber")}: {bill.billNumber}
          </div>

          <div className="print-generated-by">
            {t("generatedBy")}:{" "}
            {bill.generatedBy?.name || "-"}
          </div>
        </div>

        {/* Row 2: Customer / Form */}
        <div className="print-customer-row">
          <span className="print-customer-label">
            {t("customerForm")}:
          </span>

          <span className="customer-line"></span>
        </div>

        {/* ================================
            ITEMS TABLE
        ================================= */}

        <table className="print-table">
          <thead>
            <tr>
              <th className="serial-column">
                {t("serialNumber")}
              </th>

              <th className="item-column">
                {t("item")}
              </th>

              <th className="quantity-column">
                {t("qty")}
              </th>

              <th className="unit-column">
                {t("unit")}
              </th>

              <th className="rate-column">
                {t("rate")}
              </th>

              <th className="price-column">
                {t("price")}
              </th>
            </tr>
          </thead>

          <tbody>
            {items.map((item, index) => {
              const productName =
                getLocalizedProductName(item);

              const unitName =
                getLocalizedUnitName(item);

              const qty =
                item.quantity !== undefined &&
                item.quantity !== null
                  ? item.quantity
                  : "";

              const hasQuantity = hasValidNumber(qty);
              const hasRate = hasValidNumber(item.rate);

              const numericQty = hasQuantity
                ? Number(qty)
                : null;

              const rate = hasRate
                ? Number(item.rate)
                : null;

              const price =
                numericQty !== null &&
                rate !== null &&
                numericQty > 0 &&
                rate >= 0
                  ? numericQty * rate
                  : null;

              return (
                <tr key={item.productId ?? index}>
                  {/* Serial Number */}
                  <td className="text-center">
                    {index + 1}
                  </td>

                  {/* Product */}
                  <td>
                    {productName}

                    {item.brand && (
                      <span className="print-brand">
                        {" "}— {item.brand}
                      </span>
                    )}
                  </td>

                  {/* Quantity */}
                  <td className="text-center">
                    {qty}
                  </td>

                  {/* Unit */}
                  <td className="text-center">
                    {unitName}
                  </td>

                  {/* Rate */}
                  <td className="text-right">
                    {rate !== null && rate >= 0
                      ? `₹${rate.toLocaleString("en-IN", {
                          minimumFractionDigits: 2,
                          maximumFractionDigits: 2,
                        })}`
                      : ""}
                  </td>

                  {/* Price */}
                  <td className="text-right">
                    {price !== null
                      ? `₹${price.toLocaleString("en-IN", {
                          minimumFractionDigits: 2,
                          maximumFractionDigits: 2,
                        })}`
                      : ""}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>

        {/* ================================
            TOTAL
        ================================= */}

        {shouldShowTotal && (
          <div className="print-total">
            <span>
              {t("total")}:
            </span>

            <span className="print-total-value">
              {`₹${Number(bill.total).toLocaleString(
                "en-IN",
                {
                  minimumFractionDigits: 2,
                  maximumFractionDigits: 2,
                }
              )}`}
            </span>
          </div>
        )}
      </div>
    </div>
  );
}
